def get_stable_coord(address, township):
    ref = TOWNSHIP_COORDS.get(township, TOWNSHIP_COORDS["臺東市"])
    h = int(hashlib.md5(address.encode('utf-8')).hexdigest()[:8], 16)
    r_lat = ((h % 1000) / 1000.0 - 0.5) * 2 * ref["radius"]
    r_lng = (((h // 1000) % 1000) / 1000.0 - 0.5) * 2 * ref["radius"]
    return round(ref["lat"] + r_lat, 6), round(ref["lng"] + r_lng, 6)

def extract_township(address):
    for t in TOWNSHIP_COORDS.keys():
        if t in address or t.replace("臺", "台") in address:
            return t
    return "臺東市"

def extract_street_or_village(address):
    if not address:
        return "主要幹道"
    m = re.search(r'([^\d縣市鄉鎮]+?(?:路[一二三四五六七八九十\d]*段?|街|大道|村|里|部落|巷))', address)
    if m:
        clean = m.group(1).replace("臺東縣", "").replace("臺東市", "").replace("台東市", "")
        for t in TOWNSHIP_COORDS.keys():
            clean = clean.replace(t, "").replace(t.replace("臺", "台"), "")
        clean = clean.strip()
        if len(clean) >= 2:
            return clean[:8]
    return "市區核心"

